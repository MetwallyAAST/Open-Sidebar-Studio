export function SidebarIcon({
  name,
  ...props
}: LucideProps & { name: string }) {
  if (!name) return <span className="icon-placeholder" />;
  const Icon = iconRegistry[name as keyof typeof iconRegistry] ?? Circle;
  return <Icon aria-hidden="true" strokeWidth={1.65} {...props} />;
}
